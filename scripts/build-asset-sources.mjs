import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

export const ASSET_THRESHOLD = 131072;
export const contentPaths = ['demos', 'previews', 'docs', 'prompts', 'entries', 'data', 'agent', 'site/runtime', 'site/icons', 'asset-cache-worker.js', 'README.md', 'CONTRIBUTING.md', 'AGENTS.md'];
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mediaExtensions = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.gif', '.svg', '.mp4', '.webm', '.mp3', '.wav', '.ogg', '.m4a', '.aac', '.flac', '.woff', '.woff2', '.otf', '.ttf', '.glb', '.gltf', '.bin', '.blend', '.hdr', '.ply']);

export function buildAssetSources(sourceRoot = root, commit) {
  if (!/^[a-f\d]{40}$/i.test(commit || '')) throw new Error('Supply a full Git commit with --commit <40-digit hex>.');
  const baseUrl = `https://raw.githubusercontent.com/MIBXR/web-atlas-next/${commit}/`;
  const assets = {};
  function collect(relative) {
    const absolute = path.join(sourceRoot, relative);
    const stat = fs.statSync(absolute);
    if (stat.isDirectory()) {
      for (const name of fs.readdirSync(absolute).sort()) collect(relative + '/' + name);
    } else if (stat.isFile() && mediaExtensions.has(path.posix.extname(relative).toLowerCase()) && stat.size >= ASSET_THRESHOLD) {
      assets[relative] = {url:baseUrl + relative.split('/').map(encodeURIComponent).join('/'), bytes:stat.size};
    }
  }
  for (const relative of contentPaths) collect(relative);
  return {commit, baseUrl, thresholdBytes:ASSET_THRESHOLD, assets};
}

export function serializeAssetSources(sources) {
  return '// Generated by scripts/build-asset-sources.mjs.\nglobalThis.AtlasAssetSources = ' + JSON.stringify(sources, null, 2) + ';\n';
}

export function loadAssetSources(sourceRoot = root) {
  const text = fs.readFileSync(path.join(sourceRoot, 'data/asset-sources.js'), 'utf8');
  const match = text.match(/(?:globalThis|window|self)\.AtlasAssetSources\s*=\s*(\{[\s\S]*\})\s*;\s*$/);
  if (!match) throw new Error('data/asset-sources.js must contain the generated media map.');
  const sources = JSON.parse(match[1]);
  if (!/^[a-f\d]{40}$/i.test(sources.commit) || sources.baseUrl !== `https://raw.githubusercontent.com/MIBXR/web-atlas-next/${sources.commit}/`) throw new Error('Media URLs must use the selected Git commit.');
  return sources;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length !== 2 || args[0] !== '--commit') throw new Error('Usage: node scripts/build-asset-sources.mjs --commit <40-digit hex>');
  const sources = buildAssetSources(root, args[1]);
  fs.writeFileSync(path.join(root, 'data/asset-sources.js'), serializeAssetSources(sources), 'utf8');
  console.log(`Mapped ${Object.keys(sources.assets).length} media paths to Git commit ${sources.commit}.`);
}
